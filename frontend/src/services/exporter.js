/* ─── helpers ────────────────────────────────────────────── */

function download(blob, filename) {
  const url = URL.createObjectURL(blob);
  const a   = Object.assign(document.createElement('a'), { href: url, download: filename });
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 5000);
}

function timestamp() {
  return new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19);
}

function buildContent(payload) {
  const { final_output, ai_score, human_score, tone, word_count } = payload;
  return [
    'HUMANIZED TEXT',
    '═══════════════════════════════════════',
    '',
    final_output,
    '',
    '═══════════════════════════════════════',
    `Tone:         ${tone ?? 'N/A'}`,
    `Word count:   ${word_count ?? 'N/A'}`,
    `Human score:  ${human_score ?? 'N/A'}%`,
    `AI score:     ${ai_score ?? 'N/A'}%`,
    `Exported:     ${new Date().toLocaleString()}`,
  ].join('\n');
}

/* ─── TXT ─────────────────────────────────────────────────── */

export async function exportTxt(payload) {
  const content = buildContent(payload);
  download(new Blob([content], { type: 'text/plain' }), `humanized-${timestamp()}.txt`);
}

