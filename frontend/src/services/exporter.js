/* ─── IMAGE ───────────────────────────────────────────────── */

export async function exportImage(payload) {
  const { final_output, ai_score, human_score, tone } = payload;

  const W = 800, PADDING = 48, FONT = 14, LINE_H = FONT * 1.8;
  const canvas = document.createElement('canvas');
  const ctx    = canvas.getContext('2d');

  ctx.font = `${FONT}px 'DM Mono', monospace`;
  const maxW = W - PADDING * 2;
  const words = (final_output ?? '').split(' ');
  const lines  = [];
  let line     = '';
  for (const w of words) {
    const test = line ? `${line} ${w}` : w;
    if (ctx.measureText(test).width > maxW && line) {
      lines.push(line);
      line = w;
    } else {
      line = test;
    }
  }
  if (line) lines.push(line);

  const HEADER_H = 80;
  const BODY_H   = lines.length * LINE_H + PADDING;
  const FOOTER_H = 80;
  const H        = HEADER_H + BODY_H + FOOTER_H + PADDING;

  canvas.width  = W;
  canvas.height = H;

  // BG
  ctx.fillStyle = '#0e0e0f';
  ctx.fillRect(0, 0, W, H);

  // Border
  ctx.strokeStyle = 'rgba(255,255,255,0.1)';
  ctx.lineWidth   = 1;
  ctx.strokeRect(0.5, 0.5, W - 1, H - 1);

  // Header
  ctx.fillStyle = '#1c1c1f';
  ctx.fillRect(0, 0, W, HEADER_H);
  ctx.strokeStyle = 'rgba(255,255,255,0.07)';
  ctx.lineWidth   = 1;
  ctx.beginPath(); ctx.moveTo(0, HEADER_H); ctx.lineTo(W, HEADER_H); ctx.stroke();

  ctx.fillStyle = '#c8f564';
  ctx.font      = `500 15px 'DM Mono', monospace`;
  ctx.fillText('◈  Humanizer', PADDING, 30);

  ctx.fillStyle = '#5c5a56';
  ctx.font      = `11px 'DM Mono', monospace`;
  ctx.fillText('LangGraph AI', PADDING, 52);

  if (tone) {
    const toneLabel = tone.toUpperCase();
    const tw = ctx.measureText(toneLabel).width;
    const tx = W - PADDING - tw - 20;
    ctx.fillStyle = 'rgba(200,245,100,0.1)';
    roundRect(ctx, tx - 10, 36, tw + 20, 22, 4);
    ctx.fill();
    ctx.fillStyle = '#c8f564';
    ctx.fillText(toneLabel, tx, 52);
  }

  // Body text
  ctx.fillStyle = '#f0ede8';
  ctx.font      = `${FONT}px 'DM Mono', monospace`;
  lines.forEach((l, i) => {
    ctx.fillText(l, PADDING, HEADER_H + PADDING + i * LINE_H);
  });

  // Footer
  const fy = HEADER_H + BODY_H + PADDING;
  ctx.fillStyle = '#141416';
  ctx.fillRect(0, fy, W, FOOTER_H);
  ctx.strokeStyle = 'rgba(255,255,255,0.07)';
  ctx.lineWidth   = 1;
  ctx.beginPath(); ctx.moveTo(0, fy); ctx.lineTo(W, fy); ctx.stroke();

  // Human score
  ctx.fillStyle = '#4ade80';
  ctx.font      = `500 22px 'DM Mono', monospace`;
  ctx.fillText(`${human_score ?? 0}%`, PADDING, fy + 38);
  ctx.fillStyle = '#5c5a56';
  ctx.font      = `10px 'DM Mono', monospace`;
  ctx.fillText('HUMAN', PADDING, fy + 56);

  // AI score
  ctx.fillStyle = '#f87171';
  ctx.font      = `500 22px 'DM Mono', monospace`;
  ctx.fillText(`${ai_score ?? 0}%`, PADDING + 100, fy + 38);
  ctx.fillStyle = '#5c5a56';
  ctx.font      = `10px 'DM Mono', monospace`;
  ctx.fillText('AI', PADDING + 100, fy + 56);

  // Date
  const d = new Date().toLocaleDateString();
  ctx.fillStyle = '#5c5a56';
  ctx.font      = `10px 'DM Mono', monospace`;
  const dw = ctx.measureText(d).width;
  ctx.fillText(d, W - PADDING - dw, fy + 48);

  canvas.toBlob((blob) => {
    download(blob, `humanized-${timestamp()}.png`);
  }, 'image/png');
}

function roundRect(ctx, x, y, w, h, r) {
  ctx.beginPath();
  ctx.moveTo(x + r, y);
  ctx.lineTo(x + w - r, y);
  ctx.quadraticCurveTo(x + w, y, x + w, y + r);
  ctx.lineTo(x + w, y + h - r);
  ctx.quadraticCurveTo(x + w, y + h, x + w - r, y + h);
  ctx.lineTo(x + r, y + h);
  ctx.quadraticCurveTo(x, y + h, x, y + h - r);
  ctx.lineTo(x, y + r);
  ctx.quadraticCurveTo(x, y, x + r, y);
  ctx.closePath();
}